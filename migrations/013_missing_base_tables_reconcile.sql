    content_format           text null,
    hook_type                text null,
    tone                     text null,
    keywords                 text[] not null,
    source_followers_count   bigint null,
    views                    bigint null,
    likes                    bigint null,
    replies                  bigint null,
    reposts                  bigint null,
    quotes                   bigint null,
    engagement_total         bigint null,
    engagement_rate          numeric null,
    age_hours                numeric null,
    velocity_score           numeric null,
    trend_score              numeric null,
    why_it_works             text null,
    adaptation_angle         text null,
