-- ---------------------------------------------------------------------------
-- 3) threads_gateway_keys — hashed API keys for the Threads gateway.
--    Key MATERIAL never lives here (hash only), so this table is safe to
--    manage via migrations. Not referenced by this repo's code — used by the
--    external gateway; creation is reconciled for schema reproducibility.
-- ---------------------------------------------------------------------------
create table if not exists public.threads_gateway_keys (
    id           uuid primary key default gen_random_uuid(),
    key_name     text not null,
    key_hash     text not null,
    enabled      boolean not null default true,
    permissions  jsonb not null,
    expires_at   timestamptz null,
    last_used_at timestamptz null,
    created_at   timestamptz not null default now(),
    updated_at   timestamptz not null default now()
);

-- Non-unique: OpenAPI introspection does not reveal unique constraints, so we
-- only index key_name without asserting uniqueness (production may or may not
-- enforce it; matching column set/types is what matters for a fresh install).
create index if not exists threads_gateway_keys_key_name_idx
    on public.threads_gateway_keys (key_name);

comment on table public.threads_gateway_keys is
    'Gateway auth key registry (hashes only, never raw keys). Owned by the '
    'external Threads gateway, not threads-operator code.';

