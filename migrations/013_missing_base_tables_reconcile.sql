-- Migration 013: reconcile MISSING base tables into repository migrations (Part 5).
--
-- These tables exist in production Supabase (project ztoxaksrdbcgceyulzwm) but
-- were created by ad-hoc SQL Editor statements that were never captured as
-- repository migrations. A fresh Supabase project could therefore NOT reach the
-- production schema using migrations/001..012 alone.
--
-- Live schema was introspected 2026-09-23 via the PostgREST OpenAPI document
-- (GET /rest/v1/ with the service role) — the ONLY schema source available
-- programmatically (no postgres connection string, no Supabase CLI, no DDL
-- API). Column types/defaults below mirror production exactly.
--
-- ADDITIVE ONLY + idempotent. Safe to run on the existing production database:
--   * create table if not exists / add column if not exists — no-ops where live.
--   * Constraints are added via DO blocks that skip when a constraint of the
--     same name already exists (production may already carry equivalents).
--   * Tiada DROP, tiada ALTER pada table sedia ada besides ADD CONSTRAINT.
--
-- Ordering note: on a FRESH database, apply THIS FILE BEFORE 010/011/012,
-- because those migrations ALTER threads_trend_candidates which no earlier
-- migration creates (the gap this file closes). Division of labour on the
-- trend table: 013 creates the table; 010 owns the status lifecycle CHECK;
-- 011 owns the used_in_queue_id FK; 012 adds approval_sent_at/timed_out_at +
-- the backlog statuses/indexes. On the EXISTING production database this file
-- is a no-op for the trend table (IF NOT EXISTS + guarded grants).
--
-- Honesty caveats from introspection limits (OpenAPI reveals columns, types,
-- defaults, PKs and FKs — nothing else):
--   * id "generated by default as identity" reproduces a bigint PK with a
--     sequence; whether production uses identity vs bigserial is not visible
--     via OpenAPI. Functionally equivalent for all code paths (id is never
--     client-supplied).
--   * Secondary indexes and unique constraints beyond PKs are NOT reproduced
--     (not introspectable), except where 010/011/012 define them.

create extension if not exists pgcrypto;

